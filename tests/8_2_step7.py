"""
Сюжет:
Алон разрабатывает функцию для валидации паролей.
Пароль может содержать только латинские буквы (как заглавные, так и строчные) и цифры.
Использование букв других алфавитов и знаков препинания недопустимо.
В воздухе повисает напряжение, когда Алон, дрожащей рукой, тянется к недавно изученной библиотеке,
словно к спасительному кругу в бушующем море возможностей.

Задание:
Пользователь создал пароль и присылает вам на проверку, примите его (см. Sample Input).
Создайте функцию, которая проверит этот пароль. Что проверяет функция:
- Пароль может содержать числа или буквы латинского алфавита (большие или маленькие).
То есть пароль может состоять из чисел, или из букв, или из чисел и букв.
- Пароль не может содержать знаки препинания, пробелы и буквы другого алфавита.
Если пароль проходит проверку, то функция выводит на экран: True, иначе выводит False.
Вызовите созданную вами функцию и передайте в качестве аргумента пароль от пользователя.
Решить задачу можно любым способом, но постарайтесь воспользоваться библиотекой string.
Также, рекомендую вспомнить как работает else с циклом.
"""

import string


def check_psw(password):
    """
    Проверяет, состоит ли пароль только из латинских букв (A‑Z, a‑z) и цифр (0‑9).

    Args:
        password (str): проверяемый пароль

    Returns:
        bool: True, если пароль корректен; False — иначе
    """
    # Допустимые символы: латинские буквы и цифры
    allowed_chars = set(string.ascii_letters + string.digits)

    # Проверяем каждый символ в пароле
    for char in password:
        if char not in allowed_chars:
            return False  # Найден недопустимый символ

    # Если все символы допустимы (и пароль не пустой)
    return len(password) > 0


# Получение пароля от пользователя
user_password = input().strip()

# Проверка пароля и вывод результата
print(check_psw(user_password))
